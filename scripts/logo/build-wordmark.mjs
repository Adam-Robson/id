import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { inkBox, union } from './measure.mjs';
import { framed, glyphGroups } from './parse-logo.mjs';
import { ORB_FRAME, OUT, PRIMARY, sourceFile } from './sources.mjs';

const pct = (part, whole) => `${((part / whole) * 100).toFixed(3)}%`;

/** Where the orb sits in the wordmark's box, for the Logo component. */
function geometryModule(frame) {
  const orb = {
    left: pct(ORB_FRAME.x - frame.x, frame.w),
    top: pct(ORB_FRAME.y - frame.y, frame.h),
    width: pct(ORB_FRAME.w, frame.w),
    height: pct(ORB_FRAME.h, frame.h),
  };

  return `/**
 * Where the orb sits inside the wordmark, as percentages of the wordmark's
 * box. Generated by \`npm run logo:build\` from assets/logo; rerun it rather
 * than editing these numbers.
 */
export const LOGO_GEOMETRY = {
  aspectRatio: '${frame.w} / ${frame.h}',
  orb: {
    left: '${orb.left}',
    top: '${orb.top}',
    width: '${orb.width}',
    height: '${orb.height}',
  },
} as const;
`;
}

/**
 * Writes the lettering on its own as wordmark.svg. The site uses it as a CSS
 * mask, so only its shape matters and it takes the theme's text colour.
 */
export async function buildWordmark() {
  const svg = await readFile(sourceFile(PRIMARY), 'utf8');
  const letters = glyphGroups(svg).join('');
  const frame = union(await inkBox(letters), ORB_FRAME);

  await writeFile(
    path.join(OUT.logoDir, 'wordmark.svg'),
    framed(letters, frame, frame.w),
  );
  await writeFile(OUT.geometry, geometryModule(frame));

  return `wordmark.svg  ${frame.w}x${frame.h}`;
}
